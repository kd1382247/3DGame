#pragma once

#include <Windows.h>

// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// /////
// マウスカーソルの表示 / 非表示を指定する
// ----- ----- ----- ----- ----- ----- ----- ----- ----- -----
// Windowsの ShowCursor() は、呼んだ回数を数えるカウンターで動いている
// ・ShowCursor(true)  : カウンターが +1
// ・ShowCursor(false) : カウンターが -1
// ・カーソルが見えるのは、カウンターが 0 以上のときだけ
// そのため ShowCursor() をそのまま使うと、true と false を呼んだ回数がずれた時に、
// 消したいのに消えない (または見せたいのに見えない) ことが起きる
//
// この関数は、戻り値(呼んだ後のカウンター)を見ながら、狙った側に入るまで繰り返す
// → 何回呼んでも、同じ状態になる (呼んだ回数を気にしなくてよい)
// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// ///// /////
inline void SetCursorVisible(bool isVisible)
{
	if (isVisible)
	{
		// カウンターが 0 以上になるまで増やす
		while (ShowCursor(TRUE) < 0) {}
	}
	else
	{
		// カウンターが 0 未満になるまで減らす
		while (ShowCursor(FALSE) >= 0) {}
	}
}
